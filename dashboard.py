"""dashboard.py -- Home Electricity Saver demo.   Run:  streamlit run dashboard.py"""
from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import streamlit as st

from config import COOLING_MODES, EnvConfig
from env import RoomEnv, decode_action, encode_action
from evaluate import EVAL_SEEDS
from train import QLearningPolicy

CFG = EnvConfig()
DAY = {0: "workday", 1: "weekend"}
REGIME = {0: "dry", 1: "humid"}


class FixedPolicy:
    def __init__(self, action: int) -> None:
        self.action = action

    def select_action(self, state: tuple[int, ...]) -> int:
        return self.action


def load_policies() -> dict[str, object]:
    """Load the saved greedy policy and the deterministic Always Off baseline."""
    policies: dict[str, object] = {}
    q_table_path = Path("q_table.npy")
    if q_table_path.exists():
        policies["Q-learning"] = QLearningPolicy(
            np.load(q_table_path), config=CFG, epsilon=0.0
        )
    policies["Always Off"] = FixedPolicy(encode_action(0, 0))
    return policies


@st.cache_data
def seeds_for(day_type: int, regime: int) -> list[int]:
    """Return evaluation seeds whose generated conditions match the controls."""
    env = RoomEnv(CFG)
    matching: list[int] = []
    for seed in EVAL_SEEDS:
        _, info = env.reset(seed=seed)
        if info["day_type"] == day_type and info["weather_regime"] == regime:
            matching.append(int(seed))
    return matching


@st.cache_data
def scenario_label(seed: int) -> str:
    """Name a scenario from the conditions generated by its evaluation seed."""
    env = RoomEnv(CFG)
    _, info = env.reset(seed=seed)
    day_name = DAY.get(info["day_type"], f"day type {info['day_type']}")
    weather_name = REGIME.get(
        info["weather_regime"], f"weather regime {info['weather_regime']}"
    )
    return f"{day_name.title()} - {weather_name.title()} weather - seed {seed}"


def run_day(policy: object, seed: int) -> pd.DataFrame:
    """Run one deterministic day and retain the fields needed by the dashboard."""
    env = RoomEnv(CFG)
    state, _ = env.reset(seed=seed)
    rows: list[dict[str, object]] = []
    truncated = False
    while not truncated:
        action = policy.select_action(state)  # type: ignore[attr-defined]
        state, reward, _, truncated, info = env.step(action)
        mode, light = decode_action(action)
        rows.append(
            {
                "hour": (info["step"] - 1) * CFG.dt,
                "temp": info["indoor_temp"],
                "activity": info["activity"],
                "mode": COOLING_MODES[mode],
                "light": light,
                "energy": info["energy_kwh"],
                "cost": info["cost"],
                "d_t": info["D_T"],
                "reward": reward,
            }
        )
    return pd.DataFrame(rows)


def summarize_day(df: pd.DataFrame) -> dict[str, float]:
    """Summarize the real metrics returned by the environment."""
    return {
        "Energy (kWh)": float(df["energy"].sum()),
        "Estimated cost (INR)": float(df["cost"].sum()),
        "Discomfort (lower is better)": float(df["d_t"].sum()),
        "Total reward (higher is better)": float(df["reward"].sum()),
    }


def temperature_chart(q_df: pd.DataFrame, off_df: pd.DataFrame):
    """Plot indoor temperature for both policies on the same simulated day."""
    fig, ax = plt.subplots(figsize=(10, 4.6))
    ax.axhspan(
        CFG.t_comfort_lo,
        CFG.t_comfort_hi,
        alpha=0.16,
        color="green",
        label="Configured comfort range",
    )
    ax.plot(
        q_df["hour"] + CFG.dt,
        q_df["temp"],
        linewidth=2.2,
        label="Q-learning",
    )
    ax.plot(
        off_df["hour"] + CFG.dt,
        off_df["temp"],
        linewidth=2.0,
        linestyle="--",
        label="Always Off",
    )
    ax.set_title("Indoor temperature during the same simulated day")
    ax.set_xlabel("Hour of day")
    ax.set_ylabel("Indoor temperature (C)")
    ax.set_xlim(0, 24)
    ax.set_xticks(range(0, 25, 2))
    ax.grid(True, alpha=0.25)
    ax.legend(loc="best")
    fig.tight_layout()
    return fig


st.set_page_config(page_title="Home Electricity Saver", layout="wide")
st.title("RL-Powered Home Energy Management")
st.caption(
    "Live simulation: compare a trained Q-learning controller with an Always Off baseline."
)
st.info(
    "This is a simulation using uncalibrated placeholder parameters. "
    "The results compare controller behavior in the model; they are not measured "
    "or guaranteed real-world electricity savings."
)

policies = load_policies()
q_policy = policies.get("Q-learning")
if q_policy is None:
    st.info(
        "The trained policy file `q_table.npy` was not found. "
        "Place the saved file in this project folder; the dashboard does not retrain it."
    )
else:
    control_col1, control_col2, control_col3 = st.columns([1, 1, 2])
    with control_col1:
        selected_day = st.selectbox(
            "Day type", options=list(DAY), format_func=lambda value: DAY[value]
        )
    with control_col2:
        selected_weather = st.selectbox(
            "Weather", options=list(REGIME), format_func=lambda value: REGIME[value]
        )

    matching_seeds = seeds_for(selected_day, selected_weather)
    with control_col3:
        if matching_seeds:
            selected_seed = st.selectbox(
                "Simulated evaluation day",
                options=matching_seeds,
                format_func=scenario_label,
            )
        else:
            selected_seed = None
            st.warning(
                "No saved evaluation seed matches this combination. Choose another scenario."
            )

    if selected_seed is not None:
        with st.spinner("Simulating both controllers on the same day..."):
            q_results = run_day(q_policy, selected_seed)
            off_results = run_day(policies["Always Off"], selected_seed)

        st.subheader("Results for this simulated day")
        st.caption(
            "Both controllers use the same random seed and simulated conditions. "
            "A single day is an example, not proof of average performance."
        )
        comparison = pd.DataFrame(
            [summarize_day(q_results), summarize_day(off_results)],
            index=["Q-learning", "Always Off"],
        )
        comparison.index.name = "Controller"
        st.dataframe(comparison.round(2), use_container_width=True)

        st.subheader("What happened to indoor temperature?")
        fig = temperature_chart(q_results, off_results)
        st.pyplot(fig, use_container_width=True)
        plt.close(fig)

st.divider()
st.caption(
    "Project limitation: the environment uses uncalibrated placeholder parameters. "
    "For that reason, present all values as simulated outputs, not real household measurements."
)
